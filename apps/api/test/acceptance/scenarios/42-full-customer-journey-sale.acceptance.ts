import type { LeadDetail, ProjectDetail, SalesReport } from '@oneohm/api-contracts';
import { campaignLabel } from '@oneohm/domain';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { closeDb, rows } from '../support/db';
import { API, Session } from '../support/http';
import * as J from '../support/journey';
import { JOURNEY, onboardFromAd } from '../support/journey-onboard';
import { Transcript } from '../support/journey-transcript';
import { expectPaidNews, milestoneOf, owed, payTapOf } from '../support/money';
import { chatOf, choices, lastReply, promisedCall, replies } from '../support/onboarding';
import { quoteInput, uniquePhone } from '../support/sales';

// The full WhatsApp customer journey, second half (Steps 7-12): one customer from the Diwali
// ad (Steps 1-6 walked again; checked in 42-full-customer-journey) through the quote, the
// acceptance on WhatsApp, the project and the paid advance, to the reports and the history.
// The run writes the owner's transcript of this customer's whole journey.
const OUT = 'docs/testing/2026-11-03-whatsapp-journey-transcript.md';
// The thank-you names who starts the project (redesign §4).
const MR_THANKS =
  /^धन्यवाद ✅ \S+ आज \(किंवा पुढच्या कामाच्या दिवशी\) तुमचा प्रकल्प सुरू करतील आणि आगाऊ रकमेची पेमेंट लिंक पाठवतील\.$/;
const pdfType = { status: 200, type: expect.stringContaining('application/pdf') };

describe('The full WhatsApp customer journey: quote to paid advance', () => {
  const phone = uniquePhone();
  const family = uniquePhone();
  const t = new Transcript('WhatsApp sales cycle — one customer, end to end', phone, JOURNEY.name);
  let admin: Session;
  let j: J.JourneySetup;
  let leadId = '';
  let quote = { id: '', number: '' };
  let project: ProjectDetail;
  let sandboxUrl = '';
  let payToken = '';
  const lead = () => J.leadState(leadId);
  const advance = () => milestoneOf(project, 'quotation_accepted');

  beforeAll(async () => {
    admin = await Session.admin();
    await t.load(admin);
    j = await J.journeySetup(admin, { code: JOURNEY.code, name: JOURNEY.campaign });
    leadId = await onboardFromAd(t, j);
  });
  afterAll(async () => {
    t.write(
      OUT,
      `Generated by \`apps/api/test/acceptance/scenarios/42-full-customer-journey-sale.acceptance.ts\` from the real inbound messages and outbox rows of one acceptance run (WhatsApp log mode, Razorpay sandbox): one customer, ${JOURNEY.name}, from a click-to-WhatsApp ad to the paid advance. Buttons and list rows are shown as [Button]; files as 📄. Template messages show the approved wording with the file header and buttons Meta adds.`,
    );
    await j?.restore();
    await closeDb();
  });

  it('7. staff convert the lead, quote from it, and send the quote PDF with Accept / Question', async () => {
    t.step('7. After the call: customer, quotation, quote sent');
    const converted = await J.convertInPune(admin, j.ownerSession, leadId);
    quote = await j.ownerSession.post<{ id: string; number: string }>('/quotations', {
      propertyId: converted.propertyId,
      leadId,
      ...(await quoteInput(admin, { targetWp: 3000 })),
    });
    await j.ownerSession.post(`/quotations/${quote.id}/send`);
    await t.collect();
    const [sent, ...again] = await J.outboxOf(phone, 'quotation_sent');
    expect(again).toEqual([]);
    expect(sent?.payload).toMatchObject({
      acceptPayload: `quote_accept:${quote.id}`,
      askPayload: `quote_ask:${quote.id}`,
      // Easy to find again in the customer's WhatsApp media (live review C16).
      documentName: 'OneOhm-Ravi-Patil-test-quote.pdf',
    });
    expect(await J.fetchFile(sent?.payload.documentUrl ?? '')).toMatchObject(pdfType);
    // The approved template carries the file: no second copy as a chat file (only the estimate).
    expect(await J.outboxOf(phone, 'session:document')).toHaveLength(1);
    expect((await lead()).stage).toBe('quoted');
    t.ourSide(
      `${j.owner.name} converted the lead (customer + Pune site; audit lead.converted) and sent quotation ${quote.number} made from it: quotation_sent with the PDF header and Accept / Question buttons; lead stage ${(await lead()).stage}.`,
    );
  });

  it('8a. a family number tapping Accept is refused and handed to the owner', async () => {
    t.step('8a. A family member taps Accept');
    const app = await Session.code(phone, 'customer');
    await app.post('/customer/family', { name: 'Sunita Patil (test)', phone: family });
    t.alsoFrom(family, 'Family member (wife)');
    await t.send({ buttonPayload: `quote_accept:${quote.id}` }, family);
    const state = (await chatOf(family)).state;
    const spec = ' ⚠ Spec: a family tap on Accept hands the chat to the owner at once (check 8a).';
    t.ourSide(
      `Family chat: ${state}; quotation ${await J.statusOf('quotations', quote.id)}.${state === 'human' ? '' : spec}`,
    );
    expect((await replies(family)).flatMap(choices)).not.toContain(`quote_yes:${quote.id}`);
    expect((await chatOf(family)).state).toBe('human');
    expect(await J.statusOf('quotations', quote.id)).toBe('sent');
  });

  it('8b. the customer accepts on WhatsApp: accepted by the customer, lead won, project setup told', async () => {
    t.step('8b. The customer accepts');
    await t.send({ buttonPayload: `quote_accept:${quote.id}` });
    const check = await lastReply(phone);
    expect(choices(check)).toEqual([`quote_yes:${quote.id}`, `quote_no:${quote.id}`]);
    // The accept check says the first instalment in whole rupees, with no quote code (C1, C9).
    expect(check?.body).toMatch(/^₹[\d,]+ चे सोलर कोटेशन स्वीकारायचे\? पहिला हप्ता ₹[\d,]+ स्वीकारताना/);
    await t.tap(`quote_yes:${quote.id}`);
    expect(await J.statusOf('quotations', quote.id)).toBe('accepted');
    expect(await J.auditsOf('quotation.accepted', quote.id)).toEqual([
      {
        actor_user_id: null,
        data: expect.objectContaining({ by: 'customer', channel: 'whatsapp', phone }),
      },
    ]);
    expect((await lead()).stage).toBe('won');
    const told = await J.alerted('quotation_accepted', quote.id);
    for (const id of [j.owner.id, ...(await J.holdersOf('projects.create'))])
      expect(told).toContain(id);
    expect(
      await rows('SELECT 1 FROM outbox WHERE dedupe_key = $1', [`quote_thanks:${quote.id}`]),
    ).toHaveLength(1);
    t.ourSide(
      `Quotation accepted by the customer (audit: by customer, channel whatsapp, their phone); lead stage won; "start the project" alert to ${j.owner.name} and every projects.create holder (${told.length} people); one thank-you.${MR_THANKS.test((await lastReply(phone))?.body ?? '') ? '' : ' ⚠ From here on the bot and the templates speak English, though the customer chose मराठी (check 8c).'}`,
    );
  });

  it('8c. after becoming a customer they are still answered in the Marathi they chose', async () => {
    const [thanks] = await J.outboxOf(phone, 'session:buttons').then((sent) =>
      sent.filter((row) => row.dedupe_key === `quote_thanks:${quote.id}`),
    );
    const [sent] = await J.outboxOf(phone, 'quotation_sent');
    expect(thanks?.payload.body).toMatch(MR_THANKS);
    expect(sent?.payload.language).toBe('mr-IN');
  });

  it('9. staff start the project: the advance is due and Pay now opens the pay page', async () => {
    t.step('9. Project started, advance due');
    const created = await J.startProject(admin, quote.id);
    project = await admin.get<ProjectDetail>(`/projects/${created.id}`);
    expect(advance().status).toBe('due');
    // Her chat is open, so "please pay" is a chat message with [Pay ₹X] [I paid another way]
    // (redesign §19), not the payment_link template; [Pay ₹X] answers with the pay link.
    await t.collect();
    // "Started" names her project manager in the chat, in Marathi (redesign §19).
    const [started] = await rows<{ body: string }>(
      "SELECT payload->>'body' AS body FROM outbox WHERE recipient = $1 AND dedupe_key = $2",
      [phone, `project_started:${created.id}`],
    );
    expect(started?.body).toContain('प्रोजेक्ट मॅनेजर');
    expect(await J.outboxOf(phone, 'payment_link')).toHaveLength(0);
    const due = (await J.outboxOf(phone, 'session:buttons')).find((one) =>
      JSON.stringify(one.payload).includes(`paidother:${advance().id}`),
    );
    expect(due?.dedupe_key).toBe(`milestone_due:${advance().id}`);
    await t.tap(`pay:${advance().id}`);
    const [cta] = await J.outboxOf(phone, 'session:cta_url');
    payToken = String(cta?.payload.url ?? '').split('/pay/due/')[1] ?? '';
    expect(payToken).toBeTruthy();
    // Opening the link shows the amount in Marathi (her language); Continue opens the gateway.
    expect(await (await fetch(`${API}/pay/due/${payToken}`)).text()).toContain('पेमेंट करा');
    const go = await fetch(`${API}/pay/due/${payToken}?go=1`, { redirect: 'manual' });
    sandboxUrl = go.status === 302 ? (go.headers.get('location') ?? '') : '';
    expect(sandboxUrl).toContain('/v1/pay/sandbox/');
    await t.send({ text: 'payments' }); // Redesign §10: [Pay ₹X] answers with the pay link.
    await t.tap(await payTapOf(phone));
    expect((await J.outboxOf(phone, 'session:cta_url'))[0]?.payload.url).toContain('/pay/due/');
    t.ourSide(
      `Project ${project.code} made from the accepted quote; advance "${advance().label}" (₹${owed(advance()) / 100}) due; payment_link queued with a Pay now token that opens the Razorpay sandbox page; the Payments menu answers with a Pay now button.`,
    );
  });

  it('10. the customer pays in the sandbox: paid everywhere, receipt PDF, staff told', async () => {
    t.step('10. The customer pays');
    const paidAt = await fetch(sandboxUrl.replace(/^.*\/v1/, API), { method: 'POST' });
    expect(paidAt.status).toBeLessThan(300);
    await t.collect();
    expect(await J.statusOf('payment_milestones', advance().id)).toBe('paid');
    const [payment] = await rows<{ id: string; receipt_number: string; amount_paise: string }>(
      'SELECT id, receipt_number, amount_paise FROM payments WHERE milestone_id = $1',
      [advance().id],
    );
    expect(Number(payment?.amount_paise)).toBe(owed(advance()));
    const [received] = await J.outboxOf(phone, 'payment_received');
    const receiptFile = received?.payload.documentName ?? '';
    // Named for the customer (C16); the chat then says what is next, who to call, with taps (C6).
    await expectPaidNews(receiptFile, payment?.id ?? '', project.id);
    expect(await J.fetchFile(received?.payload.documentUrl ?? '')).toMatchObject(pdfType);
    const [owner] = await rows<{ id: string }>(
      'SELECT coalesce(manager_user_id, $2) AS id FROM projects WHERE id = $1',
      [project.id, j.owner.id],
    );
    const told = (
      await rows<{ user_id: string }>(
        `SELECT user_id FROM notifications WHERE kind = 'payment_online' AND project_id = $1`,
        [project.id],
      )
    ).map((row) => row.user_id);
    for (const id of [owner?.id, ...(await J.holdersOf('finance.record_payments'))])
      expect(told).toContain(id);
    const activity = await rows(
      `SELECT 1 FROM project_activities WHERE project_id = $1 AND kind = 'payment'`,
      [project.id],
    );
    expect(activity.length).toBeGreaterThan(0);
    const old = await fetch(`${API}/pay/due/${payToken}`, { redirect: 'manual' });
    expect(await old.text()).toContain('हे आधीच भरले आहे. धन्यवाद!');
    t.ourSide(
      `Advance paid: payment ${payment?.receipt_number} (₹${Number(payment?.amount_paise) / 100}), milestone paid, receipt sent as ${receiptFile}; payment_online alert to the project owner and accounts (${told.length} people); project activity written; the old Pay now link now says "already paid".`,
    );
  });

  it('11. the sales report and the lead page credit the Diwali campaign', async () => {
    t.step('11. Reports');
    const report = await admin.get<SalesReport>('/business-reports/sales');
    const row = report.byCampaign.find((entry) => entry.key === JOURNEY.code);
    expect(row).toMatchObject({
      label: JOURNEY.campaign,
      leads: 1,
      estimates: 1,
      quoted: 1,
      won: 1,
      collectedPaise: owed(advance()),
    });
    const detail = await admin.get<LeadDetail>(`/leads/${leadId}`);
    expect(detail.source).toBe('whatsapp');
    const label = ['WhatsApp', campaignLabel(detail.attribution)].join(' · ');
    expect(label).toBe(`WhatsApp · ${JOURNEY.campaign}`);
    t.ourSide(
      `Sales report, By campaign: "${row?.label}" — leads ${row?.leads}, estimates ${row?.estimates}, quoted ${row?.quoted}, won ${row?.won}, collected ₹${(row?.collectedPaise ?? 0) / 100}. Lead page source: "${label}".`,
    );
  });

  it('12. the lead history tells the whole sale in order; the audit log has the convert and the accept', async () => {
    t.step('12. The lead history');
    const history = await J.historyOf(leadId);
    const steps = [
      'Started onboarding on WhatsApp',
      'Site: Home',
      'Bill: ₹2,000–3,000',
      'Roof: RCC, 2 floors',
      'Bill file received on WhatsApp (not checked)',
      'Estimate sent: ',
      `Asked for a call ${promisedCall().when} after the estimate`,
      'Converted to a customer',
      `Quotation ${quote.number} sent`,
      `Quotation ${quote.number} accepted by the customer on WhatsApp`,
      'to Won',
    ];
    const at = steps.map((words) => history.findIndex((note) => note.includes(words)));
    expect(
      at.every((index) => index >= 0),
      JSON.stringify(history),
    ).toBe(true);
    expect([...at].sort((a, b) => a - b)).toEqual(at);
    const audits = await rows<{ action: string }>(
      `SELECT action FROM audit_log WHERE entity_id IN ($1, $2)
          AND action IN ('lead.converted', 'quotation.accepted') ORDER BY action`,
      [leadId, quote.id],
    );
    expect(audits.map((audit) => audit.action)).toEqual(['lead.converted', 'quotation.accepted']);
    t.ourSide(
      `Lead history, oldest first: ${history.map((note) => `“${note}”`).join(' → ')}. Audit log: lead.converted, quotation.accepted.`,
    );
  });
});
