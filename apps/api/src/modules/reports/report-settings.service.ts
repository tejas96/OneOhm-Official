import { Inject, Injectable } from '@nestjs/common';
import type { ReportSetting } from '@oneohm/api-contracts';
import { discomReportTemplates, reportSettings, taskTemplates } from '@oneohm/database';
import { asc, eq } from 'drizzle-orm';
import { recordAudit } from '../../common/audit';
import { type Actor, assertCan } from '../../common/auth/actor';
import { invalid, notFound } from '../../common/http/errors';
import { DATABASE, type Database } from '../../config/core.module';
import { BUILT_IN_REPORTS } from './report-definitions';
import { ReportFormatsStore } from './report-formats.store';

/**
 * Per report (PRD 3.18): whether the customer sees it in their app, and whether it is
 * saved to the project documents by itself when its trigger task is done. Visibility is
 * kept on each DISCOM's format (Settings → DISCOMs); a switch here sets it for every
 * DISCOM at once. Triggers are the tasks that name the report in Settings → Task templates.
 */
@Injectable()
export class ReportSettingsService {
  constructor(
    @Inject(DATABASE) private readonly db: Database,
    private readonly formats: ReportFormatsStore,
  ) {}

  async list(): Promise<ReportSetting[]> {
    const rows = await this.db.select().from(reportSettings);
    const chosen = new Map(rows.map((row) => [row.key, row]));
    const templates = await this.db
      .select({ title: taskTemplates.title, reports: taskTemplates.reports })
      .from(taskTemplates)
      .where(eq(taskTemplates.active, true))
      .orderBy(asc(taskTemplates.position));
    const definitions = await this.formats.definitions();
    const keys = [...new Set(definitions.map((definition) => definition.key))];
    return keys.map((key) => {
      const formats = definitions.filter((definition) => definition.key === key);
      const builtIn = BUILT_IN_REPORTS.find((report) => report.key === key);
      return {
        key,
        name: formats[0]?.name ?? key,
        defaultVisible: builtIn?.customerVisible ?? true,
        // Shown only when every DISCOM's format of it is shown.
        customerVisible: formats.every((definition) => definition.customerVisible),
        autoGenerate: chosen.get(key)?.autoGenerate ?? true,
        triggers: templates
          .filter((template) => template.reports.includes(key))
          .map((template) => template.title),
      };
    });
  }

  /** The reports a customer may open at any DISCOM (each project checks its own format). */
  async customerVisible(): Promise<ReadonlySet<string>> {
    const definitions = await this.formats.definitions();
    return new Set(definitions.filter((entry) => entry.customerVisible).map((entry) => entry.key));
  }

  /** The reports saved by themselves when ready (the rest wait for "Save ready reports"). */
  async autoGenerated(): Promise<ReadonlySet<string>> {
    const rows = await this.db.select().from(reportSettings);
    const off = new Set(rows.filter((row) => !row.autoGenerate).map((row) => row.key));
    const keys = (await this.formats.definitions()).map((entry) => entry.key);
    return new Set(keys.filter((key) => !off.has(key)));
  }

  async update(
    actor: Actor,
    key: string,
    change: { customerVisible?: boolean | undefined; autoGenerate?: boolean | undefined },
  ): Promise<ReportSetting> {
    assertCan(actor, 'settings.manage');
    const current = (await this.list()).find((setting) => setting.key === key);
    if (!current) throw notFound('That report');
    if (change.customerVisible === undefined && change.autoGenerate === undefined)
      throw invalid('Nothing to change.');
    const next = {
      customerVisible: change.customerVisible ?? current.customerVisible,
      autoGenerate: change.autoGenerate ?? current.autoGenerate,
    };
    await this.db.transaction(async (tx) => {
      await tx
        .insert(reportSettings)
        .values({ key, ...next, updatedByUserId: actor.userId })
        .onConflictDoUpdate({
          target: reportSettings.key,
          set: { ...next, updatedByUserId: actor.userId, updatedAt: new Date() },
        });
      if (change.customerVisible !== undefined)
        await tx
          .update(discomReportTemplates)
          .set({ customerVisible: change.customerVisible, updatedAt: new Date() })
          .where(eq(discomReportTemplates.key, key));
      await recordAudit(tx, actor.userId, 'report_setting.changed', 'report_setting', key, change);
    });
    const updated = (await this.list()).find((setting) => setting.key === key);
    if (!updated) throw notFound('That report');
    return updated;
  }
}
