import { Inject, Injectable, Logger } from '@nestjs/common';
import { documents, projects } from '@oneohm/database';
import { todayIn } from '@oneohm/shared';
import { eq } from 'drizzle-orm';
import { DATABASE, type Database } from '../../config/core.module';
import { CatalogService } from '../catalog/catalog.service';
import { CompanyAssetsService } from '../documents/company-assets.service';
import { ObjectStorageService } from '../documents/object-storage.service';
import type { ReportDefinition } from './report-definitions';
import { loadFiling, type SavedReport } from './report-filing';
import { reportFingerprint } from './report-fingerprint';
import { ReportFormatsStore } from './report-formats.store';
import { ReportPdfService } from './report-pdf.service';
import { projectReports, reportStatus } from './report-readiness';
import { ReportSettingsService } from './report-settings.service';
import { type ReportProject, ReportStatusService } from './report-status.service';
import { reportValues } from './report-values';
import { SurveyReportService } from './survey-report.service';

/**
 * `auto`: after work changes the project — only reports switched to "save by itself".
 * `manual`: "Save ready reports" — every ready report.
 */
export type RefreshMode = 'auto' | 'manual';

/**
 * Keeps every ready statutory report saved in the project's documents (PRD 3.18): saved
 * once its trigger task is done and its data complete, saved again when anything it
 * prints changes, with the earlier copy kept in the audit trail. A report marked as
 * submitted is never saved again by itself. The data's fingerprint ends the file's key.
 */
@Injectable()
export class ReportArchiveService {
  private readonly log = new Logger('Reports');

  constructor(
    @Inject(DATABASE) private readonly db: Database,
    private readonly statuses: ReportStatusService,
    private readonly catalog: CatalogService,
    private readonly pdf: ReportPdfService,
    private readonly storage: ObjectStorageService,
    private readonly survey: SurveyReportService,
    private readonly settings: ReportSettingsService,
    private readonly assets: CompanyAssetsService,
    private readonly formats: ReportFormatsStore,
  ) {}

  async refresh(
    projectId: string,
    userId: string | null,
    mode: RefreshMode = 'manual',
    only?: string,
  ): Promise<{ saved: number; unchanged: number }> {
    const context = await this.statuses.context(projectId);
    const company = await this.catalog.company();
    const values = reportValues(context, company, todayIn());
    const images = await this.assets.dataUris();
    const filing = await loadFiling(this.db, projectId);
    const automatic = mode === 'auto' ? await this.settings.autoGenerated() : null;
    // The project's DISCOM's own formats (Settings → DISCOMs).
    await this.formats.ensure(context.discomId);
    const own = projectReports(await this.formats.definitions(), context.discomId).flatMap(
      (report) => (report.definition ? [report.definition] : []),
    );
    let saved = 0;
    let unchanged = 0;
    for (const definition of own) {
      if (only && definition.key !== only) continue;
      if (reportStatus(definition, context, company).status !== 'ready') continue;
      if (automatic && !automatic.has(definition.key)) continue;
      const existing = filing.saved.get(definition.key);
      const print = reportFingerprint(definition, values, images);
      // Handed in: the filed copy is the one the DISCOM has, so it is never redone here.
      if (filing.submitted.has(definition.key) || existing?.fingerprint === print) {
        unchanged += 1;
        continue;
      }
      await this.save(projectId, definition, context, print, existing, userId);
      saved += 1;
    }
    // The approved site survey's report is filed with the papers too (PRD 3.4).
    if (!only && (await this.survey.fileIfApproved(projectId, userId))) saved += 1;
    return { saved, unchanged };
  }

  /** The same, after work changes the project; a failure is logged and never undoes the work. */
  refreshLater(projectId: string, userId: string | null): void {
    void this.refresh(projectId, userId, 'auto').catch((error: unknown) =>
      this.log.error(`Saving reports for ${projectId} failed: ${String(error)}`),
    );
  }

  private async save(
    projectId: string,
    definition: ReportDefinition,
    context: ReportProject,
    print: string,
    existing: SavedReport | undefined,
    userId: string | null,
  ): Promise<void> {
    const [project] = await this.db
      .select({ customerId: projects.customerId, propertyId: projects.propertyId })
      .from(projects)
      .where(eq(projects.id, projectId));
    const file = await this.pdf.render(projectId, definition.key);
    const storageKey = `reports/${projectId}/${definition.key}-${print}.pdf`;
    await this.storage.put(storageKey, file.content, 'application/pdf');
    await this.db.transaction(async (tx) => {
      if (existing)
        await tx
          .update(documents)
          .set({ replacedAt: new Date(), replacedByUserId: userId })
          .where(eq(documents.id, existing.id));
      await tx.insert(documents).values({
        projectId,
        customerId: project?.customerId ?? null,
        propertyId: project?.propertyId ?? null,
        category: 'statutory_report',
        source: 'report',
        checkedAt: new Date(),
        name: `${definition.name} · ${context.code}.pdf`,
        storageKey,
        contentType: 'application/pdf',
        sizeBytes: file.content.length,
        reportKey: definition.key,
        replacesDocumentId: existing?.id ?? null,
        uploadedByUserId: userId,
      });
    });
  }
}
